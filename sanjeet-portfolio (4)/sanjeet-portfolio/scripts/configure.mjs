#!/usr/bin/env node
/*
  Generates the public settings used by the added features from environment variables (or a .env file).
    cp .env.example .env     # fill in what you need
    node scripts/configure.mjs
  It rewrites: features/config.js, the SEO block in index.html (between the fx:seo markers),
  robots.txt, sitemap.xml (when SITE_URL is set) and the home link in 404.html.
  Only PUBLIC values belong here: everything ends up in files that are served to visitors.
  Needs Node 18+, no packages.
*/
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = (p) => join(root, p);

/* ---- read .env (simple KEY=VALUE lines; real environment variables win) ---- */
const env = {};
if (existsSync(file('.env'))) {
  for (const line of readFileSync(file('.env'), 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#')) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const get = (k, d = '') => (process.env[k] !== undefined ? process.env[k] : env[k] !== undefined ? env[k] : d).trim();

const problems = [];
function url(k, { https = false } = {}) {
  const v = get(k); if (!v) return '';
  try { const u = new URL(v); if (!/^https?:$/.test(u.protocol) || (https && u.protocol !== 'https:')) throw 0; return u.href.replace(/\/$/, ''); }
  catch { problems.push(`${k} is not a valid ${https ? 'https ' : ''}URL: ${v}`); return ''; }
}

const cfg = {
  siteUrl: url('SITE_URL'),
  github: { username: get('GITHUB_USERNAME', 'sanjeetkumar989159-hub') },
  contact: { email: get('CONTACT_EMAIL', 'sumitkumar989159@gmail.com'), formEndpoint: url('FORM_ENDPOINT', { https: true }) },
  analytics: { provider: get('ANALYTICS_PROVIDER').toLowerCase(), id: get('ANALYTICS_ID'), src: url('ANALYTICS_SRC', { https: true }) },
  assistant: { endpoint: url('ASSISTANT_ENDPOINT', { https: true }) },
  availability: { status: get('AVAILABILITY_STATUS'), note: get('AVAILABILITY_NOTE'), calendarUrl: url('CALENDAR_URL', { https: true }) }
};
if (!/^[A-Za-z0-9-]{1,39}$/.test(cfg.github.username)) problems.push('GITHUB_USERNAME looks invalid');
if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(cfg.contact.email)) problems.push('CONTACT_EMAIL looks invalid');
if (cfg.analytics.provider && !['plausible', 'umami', 'ga4'].includes(cfg.analytics.provider)) problems.push('ANALYTICS_PROVIDER must be plausible, umami or ga4');
if (cfg.analytics.provider && !cfg.analytics.id) problems.push('ANALYTICS_ID is required when ANALYTICS_PROVIDER is set');
if (cfg.analytics.provider === 'ga4' && !/^G-[A-Z0-9]+$/i.test(cfg.analytics.id)) problems.push('For ga4, ANALYTICS_ID must look like G-XXXXXXXXXX');
if (!cfg.analytics.provider) { cfg.analytics.id = ''; cfg.analytics.src = ''; }
if (problems.length) { console.error('Configuration problems:\n - ' + problems.join('\n - ')); process.exit(1); }

/* ---- features/config.js ---- */
const header = `/*
  Runtime settings for the added features. GENERATED by scripts/configure.mjs from environment variables,
  but you can also edit it by hand. Everything here is public (it is shipped to the browser).
  Never put secrets in it. Anything left empty simply switches that optional part off.
*/
`;
writeFileSync(file('features/config.js'), header + 'window.PORTFOLIO_CONFIG = ' + JSON.stringify(cfg, null, 2) + ';\n');

/* ---- SEO block ---- */
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const site = cfg.siteUrl;
const abs = (p) => (site ? `${site}/${p}` : p);
const title = 'Sanjeet Kumar · Data Analyst Portfolio';
const desc = 'Sanjeet Kumar is a Computer Science student building a career in data analytics. Python, SQL, Power BI and Excel, project case studies, certificates and resume.';
const ld = {
  '@context': 'https://schema.org', '@type': 'Person', name: 'Sanjeet Kumar', description: desc,
  ...(site ? { url: site + '/', image: abs('assets/portrait.webp') } : {}),
  email: 'mailto:' + cfg.contact.email,
  address: { '@type': 'PostalAddress', addressLocality: 'Giridih', addressRegion: 'Jharkhand', addressCountry: 'IN' },
  alumniOf: { '@type': 'CollegeOrUniversity', name: 'SAGE University Bhopal' },
  knowsAbout: ['Data analysis', 'Python', 'SQL', 'Power BI', 'Microsoft Excel', 'Pandas', 'NumPy'],
  sameAs: [`https://github.com/${cfg.github.username}`, 'https://www.linkedin.com/in/sanjeet-kumar-706597s/', 'https://leetcode.com/u/sanjeet1234/']
};
const seo = [
  `<meta name="description" content="${esc(desc)}">`,
  '<meta name="author" content="Sanjeet Kumar">',
  '<meta name="theme-color" content="#FFFFFF">',
  '<meta name="robots" content="index, follow, max-image-preview:large">',
  ...(site ? [`<link rel="canonical" href="${esc(site)}/">`] : []),
  '<link rel="icon" href="assets/favicon.svg" type="image/svg+xml">',
  '<meta property="og:type" content="website">',
  '<meta property="og:site_name" content="Sanjeet Kumar">',
  `<meta property="og:title" content="${esc(title)}">`,
  `<meta property="og:description" content="${esc(desc)}">`,
  ...(site ? [`<meta property="og:url" content="${esc(site)}/">`] : []),
  `<meta property="og:image" content="${esc(abs('assets/og-image.png'))}">`,
  '<meta property="og:image:width" content="1200">',
  '<meta property="og:image:height" content="630">',
  '<meta property="og:image:alt" content="Sanjeet Kumar, data analyst: Python, SQL, Power BI">',
  '<meta name="twitter:card" content="summary_large_image">',
  `<meta name="twitter:title" content="${esc(title)}">`,
  `<meta name="twitter:description" content="${esc(desc)}">`,
  `<meta name="twitter:image" content="${esc(abs('assets/og-image.png'))}">`,
  `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>`
].join('\n');
const idx = readFileSync(file('index.html'), 'utf8');
const re = /<!-- fx:seo:start -->[\s\S]*?<!-- fx:seo:end -->/;
if (!re.test(idx)) { console.error('SEO markers not found in index.html'); process.exit(1); }
writeFileSync(file('index.html'), idx.replace(re, () => `<!-- fx:seo:start -->\n${seo}\n<!-- fx:seo:end -->`));

/* ---- robots.txt + sitemap.xml ---- */
writeFileSync(file('robots.txt'), `User-agent: *\nAllow: /\n${site ? `\nSitemap: ${site}/sitemap.xml\n` : ''}`);
if (site) {
  writeFileSync(file('sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>${site}/</loc></url>\n</urlset>\n`);
} else if (existsSync(file('sitemap.xml'))) {
  writeFileSync(file('sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"></urlset>\n`);
}

/* ---- 404 page home link ---- */
if (existsSync(file('404.html'))) {
  const n = readFileSync(file('404.html'), 'utf8');
  writeFileSync(file('404.html'), n.replace(/(<meta name="fx-site" content=")[^"]*(">)/, (_, a, b) => a + esc(site) + b));
}

console.log('Configured:', JSON.stringify({ siteUrl: site || '(not set)', github: cfg.github.username, analytics: cfg.analytics.provider || 'off', formEndpoint: cfg.contact.formEndpoint ? 'set' : 'mailto fallback', assistantEndpoint: cfg.assistant.endpoint ? 'set' : 'local FAQ only', availability: cfg.availability.status || '(not stated)' }, null, 2));
